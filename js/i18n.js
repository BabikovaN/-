export function t(key, params = {}) {
  const lang = getLang();
  let s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), STR[lang]);
  if (s === undefined) s = key.split('.').reduce((o, k) => (o ? o[k] : undefined), STR.uk) ?? key;
  if (typeof s === 'string') for (const [k, v] of Object.entries(params)) s = s.replaceAll('{' + k + '}', v);
  return s;
}

